def _soft(rows):
    """The face's soft-knocked corners: each outer corner pixel of the glyph's box goes (a toy-package die-cut feel)."""
    r = [list(x) for x in rows]; h = min(len(r), CAP); w = len(r[0])
    for y, x in ((0, 0), (0, w - 1), (h - 1, 0), (h - 1, w - 1)):
        if w > 3 and r[y][x] == '#': r[y][x] = '.'
    return [''.join(x) for x in r]


GLYPHS = {}
for _k, _v in _SRC.items():
    _r = [l for l in _v.strip('\n').split('\n')]
    assert len(set(map(len, _r))) == 1, _k
    GLYPHS[_k] = _soft(_r)


def glyph(ch):
    """-> (rows of '#'/'.', advance px, baseline row) for ch (unknown chars read as '?', space is blank)."""
    if ch == ' ': return ['.' * SPACE] * CAP, SPACE, CAP
    g = GLYPHS.get(ch.upper()) or GLYPHS['?']
    return g, len(g[0]) + TRACK, CAP


def bdf(path):
    """A BDF bitmap font of the face (for tools that want a real font file)."""
    out = ['STARTFONT 2.1', 'FONT -gachagarage-GG Display-Bold-R-Normal--18-180-75-75-P-130-ISO10646-1', 'SIZE 18 75 75',
           'FONTBOUNDINGBOX 19 18 0 -2', 'STARTPROPERTIES 4', 'FONT_ASCENT 16', 'FONT_DESCENT 2', 'COPYRIGHT "Gacha Garage, hand-pixelled"',
           'DEFAULT_CHAR 63', 'ENDPROPERTIES']
    chars = [' '] + sorted(GLYPHS)
    out.append('CHARS %d' % len(chars))
    for ch in chars:
        rows, adv, _ = glyph(ch); w = len(rows[0]); bw = (w + 7) // 8 * 8
        out += ['STARTCHAR U+%04X' % ord(ch), 'ENCODING %d' % ord(ch), 'SWIDTH %d 0' % (adv * 1000 // 18), 'DWIDTH %d 0' % adv,
                'BBX %d %d 0 %d' % (w, len(rows), CAP - len(rows)), 'BITMAP']
        out += ['%0*X' % (bw // 4, int(r.replace('#', '1').replace('.', '0').ljust(bw, '0'), 2)) for r in rows]
        out.append('ENDCHAR')
    out.append('ENDFONT')
    open(path, 'w').write('\n'.join(out) + '\n')


def specimen(path, scale=3):
    from PIL import Image, ImageDraw
    import numpy as np
    lines = ['ABCDEFGHIJKLM', 'NOPQRSTUVWXYZ', "0123456789 !?'&-.,", 'CRABS IN FOOD CANS', "WHO'S IN THE SUIT?",
             'WORLD TOUR TURTLES', 'MAKE WAVES, KRAB!']
    ink, paper, col = (38, 30, 34), (243, 234, 214), (200, 64, 42)
    def mask(s):
        cols, x = [], 0
        for ch in s:
            rows, adv, _ = glyph(ch)
            cols.append((rows, x)); x += adv
        m = np.zeros((CAP + 2, max(x, 1)), bool)
        for rows, x0 in cols:
            for y, r in enumerate(rows):
                for xx, c in enumerate(r):
                    if c == '#': m[y, x0 + xx] = True
        return m
    ms = [mask(l) for l in lines]; W = max(m.shape[1] for m in ms) + 8; H = sum(m.shape[0] + 6 for m in ms) + 18
    im = np.zeros((H, W, 3), np.uint8); im[:] = paper
    y = 14
    for i, m in enumerate(ms):
        c = ink if i < 3 else col
        if i >= 3:  # a 1 px ink keyline + hard drop shadow, as on the cards
            sh = np.zeros_like(m); sh[1:, 1:] = m[:-1, :-1]
            im[y + 1:y + 1 + m.shape[0], 5:5 + m.shape[1]][sh] = ink
        im[y:y + m.shape[0], 4:4 + m.shape[1]][m] = c
        y += m.shape[0] + 6
    I = Image.fromarray(im).resize((W * scale, H * scale), Image.NEAREST)
    d = ImageDraw.Draw(I)
    sub = mask('GG DISPLAY  16PX CAPS  HAND-PIXELLED')
    small = np.zeros((sub.shape[0], sub.shape[1]), bool); small[:] = sub
    for yy, xx in zip(*np.nonzero(small)): d.rectangle([4 * scale + xx, 3 + yy, 4 * scale + xx, 3 + yy], fill=ink)
    I.save(path)


