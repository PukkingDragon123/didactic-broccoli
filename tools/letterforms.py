"""letterforms.py: the print studio's hand-pixelled headline lettering (POSTER-3 system, docs/ref/posters.md).
Each poster and card has its own alphabet, drawn pixel by pixel at its FINAL size (one character = one output pixel,
never scaled, never smoothed): '#' ink, '.' empty. Only the letters a title uses are drawn. The lettering is printed
as ONE flat ink (or knocked out of an ink field to the paper): no outline, no shadow, no glow, no gradient, no bevel.

  word(S, alpha, text, x, y, col, anchor='lt', track=None, bounce=None) -> (x0, y0, x1, y1)
  width(alpha, text, track=None)
"""
import numpy as np
from printkit import rgb

ALPHA = {}  # name -> {'track': px between letters, 'space': px, 'g': {char: rows}}


def alpha(name, track=1, space=5, **glyphs):
    ALPHA[name] = {'track': track, 'space': space, 'g': {}}
    return ALPHA[name]['g']


def _pad(g):
    for k, rows in g.items():
        w = max(len(r) for r in rows); g[k] = [r.ljust(w, '.') for r in rows]


