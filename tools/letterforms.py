def _glyph(al, ch, lean=0):
    rows = ALPHA[al]['g'].get(ch)
    if rows is None: return None
    g = np.array([list(r) for r in rows])
    if lean:  # an italic lean drawn as the letterer would: each row stepped right, 1 px every `lean` rows up
        H = g.shape[0]; sh = [(H - 1 - j) // lean for j in range(H)]; out = np.full((H, g.shape[1] + sh[0]), '.')
        for j in range(H): out[j, sh[j]:sh[j] + g.shape[1]] = g[j]
        g = out
    return g


def width(al, text, track=None, lean=0):
    return mask(al, text, track, lean=lean)[0].shape[1]


def mask(al, text, track=None, bounce=None, kern=None, lean=0, rise=0):
    """The word as a char array ('#' ink, 'x' / 'o' accent inks, '.' empty) and the baseline row.
    bounce: per-letter baseline offsets (cycled); kern: {letter index: extra px after it}; lean: italic, 1 px per
    `lean` rows; rise: the baseline climbs 1 px every `rise` px to the right (letters stay upright)."""
    A = ALPHA[al]; tr = A['track'] if track is None else track
    parts, x = [], 0
    for i, ch in enumerate(text):
        if ch == ' ': x += A['space']; continue
        g = _glyph(al, ch, lean)
        if g is None: continue
        dy = (bounce[i % len(bounce)] if bounce else 0) - (x // rise if rise else 0)
        parts.append((g, x, dy)); x += g.shape[1] + tr + ((kern or {}).get(i, 0)) - (lean and (len(g) - 1) // lean)
    top = min(dy for _, _, dy in parts); H = max(dy + g.shape[0] for g, _, dy in parts) - top
    W = max(px + g.shape[1] for g, px, _ in parts)
    m = np.full((H, W), '.')
    for g, px, dy in parts:
        sub = m[dy - top:dy - top + g.shape[0], px:px + g.shape[1]]
        sub[g != '.'] = g[g != '.']
    return m, -top


def word(S, al, text, x, y, col, accent=None, accent2=None, anchor='lt', border=None, **kw):
    """Print the word in one flat ink (accents: the motif letter's own inks). (x, y) anchors the word's box.
    Returns the box (x0, y0, x1, y1)."""
    m, _ = mask(al, text, **kw)
    H, W = m.shape
    X = int(round(x - {'l': 0, 'm': W / 2, 'r': W}[anchor[0]])); Y = int(round(y - {'t': 0, 'm': H / 2, 'b': H}[anchor[1]]))
    if border:  # the gashapon logo's die-cut border: ONE solid rim (r px, one colour) round the whole word
        from pixprint import _dilate
        r, bc = border
        S._stamp(_dilate(m != '.', r, 'disc' if r > 1 else 'sq'), X - r, Y - r, bc)
    S._stamp(m == '#', X, Y, col)
    if (m == 'x').any(): S._stamp(m == 'x', X, Y, accent if accent is not None else col)
    if (m == 'o').any(): S._stamp(m == 'o', X, Y, accent2 if accent2 is not None else col)
    return (X, Y, X + W, Y + H)
