const cache = new Map();
export function iconPx(name) {
  if (cache.has(name)) return cache.get(name);
  const rows = ICONS[name];
  if (!rows) return null;
  const w = rows[0].length, h = rows.length, d = new Uint8ClampedArray(w * h * 4);
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    const c = PAL[ch];
    if (c == null) return;
    const i = (y * w + x) * 4;
    d[i] = (c >> 16) & 255; d[i + 1] = (c >> 8) & 255; d[i + 2] = c & 255; d[i + 3] = 255;
  }));
  const px = { w, h, d };
  cache.set(name, px);
  return px;
}
