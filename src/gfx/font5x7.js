const FONT = {};
for (const [ch, rows] of Object.entries(GLYPHS)) { const r = rows.split('|'); FONT[ch] = { w: r[0].length, rows: r }; }
const ALIAS = { '’': '\'', '‘': '\'', '“': '"', '”': '"', '–': '-', '—': '-', 'Ū': 'U', 'ū': 'U', '…': '...', 'é': 'E' };
const norm = (s) => [...String(s)].map((ch) => ALIAS[ch] ?? ch).join('').toUpperCase();
const glyph = (ch) => FONT[ch] || FONT['?'];

/** Width in pixels of one line at scale s. */
export function textW5(str, s = 1) {
  let w = 0;
  for (const ch of norm(str)) w += (glyph(ch).w + 1) * s;
  return Math.max(0, w - s);
}

/** Draw bitmap text. o: { s (scale), col, align, lh (pixels between lines, default 3 x s), max (shrinks s to fit) }. Returns { w, h, s }. */
export function draw5(g, str, x, y, o = {}) {
  const lines = String(str).split('\n');
  let s = o.s || 1;
  if (o.max) while (s > 1 && Math.max(...lines.map((l) => textW5(l, s))) > o.max) s--;
  g.save(); g.fillStyle = o.col || '#1a1420';
  let yy = y, wmax = 0;
  for (const line of lines) {
    const lw = textW5(line, s);
    wmax = Math.max(wmax, lw);
    let xx = Math.round(o.align === 'center' ? x - lw / 2 : o.align === 'right' ? x - lw : x);
    for (const ch of norm(line)) {
      const gl = glyph(ch);
      gl.rows.forEach((row, ry) => { for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') g.fillRect(xx + rx * s, yy + ry * s, s, s); });
      xx += (gl.w + 1) * s;
    }
    yy += 7 * s + (o.lh ?? 3 * s);
  }
  g.restore();
  return { w: wmax, h: yy - y - (o.lh ?? 3 * s), s };
}

/** The lit pixels of one line at scale 1, relative to its top-left. */
export function mask5(str) {
  const out = [];
  let xx = 0;
  for (const ch of norm(str)) {
    const gl = glyph(ch);
    gl.rows.forEach((row, ry) => { for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') out.push([xx + rx, ry]); });
    xx += gl.w + 1;
  }
  return out;
}
